pub(super) fn fault_items() -> Vec<FaultItem> {
    let templated = TEMPLATES
        .iter()
        .flat_map(|(context, lines, hole, template, open)| {
            TOKEN_FAULTS
                .iter()
                .filter(move |(_, fault_hole, _)| fault_hole == hole)
                .map(move |(code, _, token)| {
                    (
                        *code,
                        *context,
                        *lines,
                        template.replacen("{}", token, 1),
                        *open,
                    )
                })
        });
    let written = ROWS.iter().map(|(code, context, lines, text, open)| {
        (*code, *context, *lines, text.to_string(), *open)
    });
    templated
        .chain(written)
        .map(|(code, context, lines, marked, open)| {
            let (text, faults) = unmark(code, &marked);
            FaultItem {
                code,
                context,
                lines,
                text,
                faults,
                open,
            }
        })
        .collect()
}

pub(super) fn unmark(code: Code, marked: &str) -> (String, Vec<(Code, Range<u32>)>) {
    let mut text = String::new();
    let mut faults = Vec::new();
    let mut start = 0;
    for c in marked.chars() {
        match c {
            '⟦' => start = text.len(),
            '⟧' => faults.push((code, start as u32..text.len() as u32)),
            _ => text.push(c),
        }
    }
    (text, faults)
}
