#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Debug)]
#[repr(u16)]
pub enum SyntaxKind {
    Whitespace,
    Comment,
    Newline,
    Indent,
    Dedent,
    Ident,
    Number,
    StringStart,
    StringText,
    StringEnd,
    InterpStart,
    InterpEnd,
    Error,
    InputKw,
    LetKw,
    FnKw,
    PatternKw,
    DefaultKw,
    IfKw,
    ThenKw,
    ElseKw,
    MatchKw,
    WhenKw,
    ForKw,
    InKw,
    AsKw,
    IsKw,
    NotKw,
    AndKw,
    OrKw,
    DivKw,
    ToKw,
    TrueKw,
    FalseKw,
    I32Kw,
    I64Kw,
    F32Kw,
    F64Kw,
    BoolKw,
    LParen,
    RParen,
    LBracket,
    RBracket,
    Comma,
    Colon,
    Colon2,
    Eq,
    Pipe,
    Slash,
    Dot,
    Dot2,
    Plus,
    Minus,
    Star,
    Star2,
    Percent,
    Lt,
    Le,
    Gt,
    Ge,
    Bang,
    Quote,
    Question,
    Tilde,
    At,
    Dollar,
}

impl SyntaxKind {
    pub const ALL: &'static [SyntaxKind] = &[
        SyntaxKind::Whitespace,
        SyntaxKind::Comment,
        SyntaxKind::Newline,
        SyntaxKind::Indent,
        SyntaxKind::Dedent,
        SyntaxKind::Ident,
        SyntaxKind::Number,
        SyntaxKind::StringStart,
        SyntaxKind::StringText,
        SyntaxKind::StringEnd,
        SyntaxKind::InterpStart,
        SyntaxKind::InterpEnd,
        SyntaxKind::Error,
        SyntaxKind::InputKw,
        SyntaxKind::LetKw,
        SyntaxKind::FnKw,
        SyntaxKind::PatternKw,
        SyntaxKind::DefaultKw,
        SyntaxKind::IfKw,
        SyntaxKind::ThenKw,
        SyntaxKind::ElseKw,
        SyntaxKind::MatchKw,
        SyntaxKind::WhenKw,
        SyntaxKind::ForKw,
        SyntaxKind::InKw,
        SyntaxKind::AsKw,
        SyntaxKind::IsKw,
        SyntaxKind::NotKw,
        SyntaxKind::AndKw,
        SyntaxKind::OrKw,
        SyntaxKind::DivKw,
        SyntaxKind::ToKw,
        SyntaxKind::TrueKw,
        SyntaxKind::FalseKw,
        SyntaxKind::I32Kw,
        SyntaxKind::I64Kw,
        SyntaxKind::F32Kw,
        SyntaxKind::F64Kw,
        SyntaxKind::BoolKw,
        SyntaxKind::LParen,
        SyntaxKind::RParen,
        SyntaxKind::LBracket,
        SyntaxKind::RBracket,
        SyntaxKind::Comma,
        SyntaxKind::Colon,
        SyntaxKind::Colon2,
        SyntaxKind::Eq,
        SyntaxKind::Pipe,
        SyntaxKind::Slash,
        SyntaxKind::Dot,
        SyntaxKind::Dot2,
        SyntaxKind::Plus,
        SyntaxKind::Minus,
        SyntaxKind::Star,
        SyntaxKind::Star2,
        SyntaxKind::Percent,
        SyntaxKind::Lt,
        SyntaxKind::Le,
        SyntaxKind::Gt,
        SyntaxKind::Ge,
        SyntaxKind::Bang,
        SyntaxKind::Quote,
        SyntaxKind::Question,
        SyntaxKind::Tilde,
        SyntaxKind::At,
        SyntaxKind::Dollar,
    ];

    pub fn from_raw(raw: u16) -> Option<SyntaxKind> {
        SyntaxKind::ALL.get(usize::from(raw)).copied()
    }

    pub fn is_trivia(self) -> bool {
        matches!(self, SyntaxKind::Whitespace | SyntaxKind::Comment)
    }

    pub fn keyword(text: &str) -> Option<SyntaxKind> {
        Some(match text {
            "input" => SyntaxKind::InputKw,
            "let" => SyntaxKind::LetKw,
            "fn" => SyntaxKind::FnKw,
            "pattern" => SyntaxKind::PatternKw,
            "default" => SyntaxKind::DefaultKw,
            "if" => SyntaxKind::IfKw,
            "then" => SyntaxKind::ThenKw,
            "else" => SyntaxKind::ElseKw,
            "match" => SyntaxKind::MatchKw,
            "when" => SyntaxKind::WhenKw,
            "for" => SyntaxKind::ForKw,
            "in" => SyntaxKind::InKw,
            "as" => SyntaxKind::AsKw,
            "is" => SyntaxKind::IsKw,
            "not" => SyntaxKind::NotKw,
            "and" => SyntaxKind::AndKw,
            "or" => SyntaxKind::OrKw,
            "div" => SyntaxKind::DivKw,
            "to" => SyntaxKind::ToKw,
            "true" => SyntaxKind::TrueKw,
            "false" => SyntaxKind::FalseKw,
            "i32" => SyntaxKind::I32Kw,
            "i64" => SyntaxKind::I64Kw,
            "f32" => SyntaxKind::F32Kw,
            "f64" => SyntaxKind::F64Kw,
            "bool" => SyntaxKind::BoolKw,
            _ => return None,
        })
    }
}
