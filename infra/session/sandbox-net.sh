#!/usr/bin/env bash
# Put this sandbox on the tailnet so `ssh wb` works, and keep it there — run by
# the SessionStart and UserPromptSubmit hooks (docs/RUNBOOK.md, "Sandbox network
# (Claude Code on the web)", has the setup script and the settings.json).
#
# ON EVERY PROMPT because a web session is a fresh VM and a process a tool call
# starts does not survive the turn; NEARLY SILENT because hook stdout is context
# on each of those prompts, so one short line only when something changed or is
# broken; ALWAYS EXIT 0 — no tailnet is a thing to report, not to fail on.
set -u

# A local checkout has its own network and its own ~/.ssh. Touch neither.
[ "${CLAUDE_CODE_REMOTE:-}" = "true" ] || exit 0

TS_DIR="${WB_TS_DIR:-/opt/ts}"
STATE_DIR="${WB_TS_STATE_DIR:-/root/.tailscale}"
SSH_DIR="${WB_SSH_DIR:-${HOME:-/root}/.ssh}"
SERVER_IP="${WB_SERVER_IP:-100.66.213.38}"
WB2_SERVER_IP="${WB2_SERVER_IP:-100.89.147.117}"
SOCKS_PORT="${WB_SOCKS_PORT:-1055}"
WAIT_SECS="${WB_NET_WAIT_SECS:-20}"
TS_HOSTNAME="${WB_TS_HOSTNAME:-claude-sandbox}"
# One command line so that a test can replace the whole thing; `nc -x` makes the
# same SOCKS5 hop that ssh will.
PROBE_CMD="${WB_PROBE_CMD:-timeout 8 nc -x localhost:$SOCKS_PORT -z $SERVER_IP 22}"
# How a running daemon is found; a test names its own so the answer never
# depends on whether THIS machine happens to run a tailscaled (row 261).
PGREP_CMD="${WB_PGREP_CMD:-pgrep}"
SOCKET="$STATE_DIR/tailscaled.sock"
LOG="$STATE_DIR/hook.log"
BEGIN_MARK='# >>> sandbox-net (managed) >>>'
END_MARK='# <<< sandbox-net (managed) <<<'
# Set by anything that was not already so: the quiet path depends on it.
CHANGED=0
# Why daemon_is_stale() said stop — put in hook.log by heal_stale_daemon().
STALE_REASON=''

say() { printf 'sandbox-net: %s\n' "$*"; }
log() { printf '[%s] %s\n' "$(date -u +%H:%M:%S)" "$*" >>"$LOG"; }
# shellcheck disable=SC2086 # PROBE_CMD is a command line; splitting it is the point
probe_ok() { $PROBE_CMD >>"$LOG" 2>&1; }

# `nc -x` is how ssh reaches a userspace tailnet: no TUN device, only a SOCKS5 port.
ssh_host() {
  cat <<EOF
Host $1
  HostName ${3:-$SERVER_IP}
  User $2
  ProxyCommand nc -x localhost:$SOCKS_PORT %h %p
  StrictHostKeyChecking accept-new
  ConnectTimeout 25
  ServerAliveInterval 30
  BatchMode yes
EOF
}

# Our block, rewritten; every other line kept — including the blank ones, which
# the awk trims off the end so that a second run cannot grow the file by one.
ensure_ssh_config() {
  local cfg="$SSH_DIR/config" tmp
  mkdir -p "$SSH_DIR" && chmod 700 "$SSH_DIR"
  tmp="$(mktemp)"
  [ -f "$cfg" ] && awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
    $0 == b { drop = 1 } drop { if ($0 == e) drop = 0; next }
    /^[[:space:]]*$/ { blanks++; next }
    { while (blanks-- > 0) print ""; blanks = 0; print }' "$cfg" >"$tmp"
  [ -s "$tmp" ] && printf '\n' >>"$tmp"
  { printf '%s\n' "$BEGIN_MARK"; ssh_host wb tornike; printf '\n'
    ssh_host wb-root root; printf '\n'
    ssh_host wb2 root "$WB2_SERVER_IP"; printf '%s\n' "$END_MARK"; } >>"$tmp"
  if [ -f "$cfg" ] && cmp -s "$tmp" "$cfg"; then
    rm -f "$tmp"
  else
    mv "$tmp" "$cfg" && CHANGED=1 && log "wrote the managed block in $cfg"
  fi
  chmod 600 "$cfg" 2>/dev/null
}

# A file rather than an inline `bash -c`, so a session can read what keeps the
# daemon up; rewritten every run so an edit here reaches a loop already running,
# and RENAMED into place rather than truncated because bash reads a running
# script by offset — rewriting it under a live loop would corrupt that loop.
write_supervisor() {
  cat >"$STATE_DIR/supervise.sh.new" <<EOF
#!/usr/bin/env bash
# Generated by infra/session/sandbox-net.sh — edit that, not this. The socket
# outlives a killed daemon, and the next one would refuse to start over it.
echo \$\$ >"$STATE_DIR/supervise.pid"
while :; do
  rm -f "$SOCKET"
  "$TS_DIR/tailscaled" --tun=userspace-networking \\
    --socks5-server=localhost:$SOCKS_PORT --outbound-http-proxy-listen=localhost:1056 \\
    --state="$STATE_DIR/tailscaled.state" --socket="$SOCKET" >>"$STATE_DIR/tailscaled.log" 2>&1
  sleep 3
done
EOF
  mv "$STATE_DIR/supervise.sh.new" "$STATE_DIR/supervise.sh"
}

# A live supervisor means the daemon is only mid-restart (the loop pauses 3 s);
# a second one is two daemons over one socket. Pids are reused, so a live pid is
# only evidence of that when the process behind it is the supervisor — which is
# also why heal_stale_daemon() below asks this for the pid to kill rather than
# trusting the pid file on its own.
supervisor_pid() {
  local pid; pid="$(cat "$STATE_DIR/supervise.pid" 2>/dev/null)"
  [ -n "$pid" ] || return 1
  kill -0 "$pid" 2>/dev/null || return 1
  tr '\0' ' ' <"/proc/$pid/cmdline" 2>/dev/null | grep -qF supervise.sh || return 1
  printf '%s' "$pid"
}
supervisor_alive() { supervisor_pid >/dev/null; }

# BackendState, or nothing at all while the daemon is not answering yet.
backend_state() {
  "$TS_DIR/tailscale" --socket="$SOCKET" status --json 2>>"$LOG" |
    python3 -c 'import json,sys; print(json.load(sys.stdin).get("BackendState",""))' 2>>"$LOG"
}

# "Starting" is a daemon that loaded existing state and is still connecting: it
# is waited out, because logging in over it would re-authenticate a node that
# already is. Past the deadline, whatever was last seen is the answer.
wait_for_state() {
  local deadline=$((SECONDS + WAIT_SECS)) state=''
  while :; do
    state="$(backend_state)"
    [ -n "$state" ] && [ "$state" != "Starting" ] && break
    [ "$SECONDS" -ge "$deadline" ] && break
    sleep 1
  done
  printf '%s' "$state"
}

# BackendState, whether Self answers Online, and any health-check text, from
# one status call — the shape tailscaled leaves behind when it is still
# dialing a proxy port the harness closed on restart: it never notices by
# itself, so only the symptom (Running, but Self never came back, and the
# coordination server names the trouble) says so.
self_offline_with_coordination_issue() {
  local out lines
  out="$("$TS_DIR/tailscale" --socket="$SOCKET" status --json 2>>"$LOG" |
    python3 -c 'import json,sys
d=json.load(sys.stdin)
print(d.get("BackendState",""))
print("yes" if (d.get("Self") or {}).get("Online") else "no")
print(" ".join(d.get("Health") or []))' 2>>"$LOG")"
  mapfile -t lines <<<"$out"
  [ "${lines[0]:-}" = "Running" ] || return 1
  [ "${lines[1]:-}" = "no" ] || return 1
  printf '%s' "${lines[2]:-}" | grep -qi 'coordination server'
}

# True when the daemon `pgrep` just found is the one from BEFORE a harness
# restart: the agent proxy comes back on a new port, but this process (and its
# supervisor) survived with the old one in its environment, so every dial goes
# to a port that is now closed and nothing here notices on its own. Sets
# STALE_REASON for the one line heal_stale_daemon() logs. With no HTTPS_PROXY
# to compare in THIS run, the question does not apply — this hook is not
# running under a proxied harness — so nothing here is ever called stale.
daemon_is_stale() {
  local pid="$1" recorded
  [ -n "${HTTPS_PROXY:-}" ] || return 1
  recorded="$(cat "/proc/$pid/environ" 2>/dev/null | tr '\0' '\n' | sed -n 's/^HTTPS_PROXY=//p')"
  if [ "$recorded" != "$HTTPS_PROXY" ]; then
    STALE_REASON="its HTTPS_PROXY was '$recorded', now '$HTTPS_PROXY'"
    return 0
  fi
  if self_offline_with_coordination_issue && ! probe_ok; then
    STALE_REASON='Running but Self is offline (coordination-server health check) and wb is unreachable'
    return 0
  fi
  return 1
}

# The manual fix, done by the hook: neither process notices its proxy died, so
# both are stopped by the PIDs already on record — never by name, which could
# just as well hit another sandbox's tailscaled sharing this box — the stale
# socket is cleared the way a fresh supervisor loop would clear it anyway, and
# a new pair starts under THIS run's environment. The state dir (and its keys)
# is untouched, so it comes back with no re-auth.
heal_stale_daemon() {
  local pid="$1" sup
  sup="$(supervisor_pid)"
  [ -n "$sup" ] && kill "$sup" 2>/dev/null
  kill "$pid" 2>/dev/null
  rm -f "$SOCKET"
  setsid nohup bash "$STATE_DIR/supervise.sh" >/dev/null 2>&1 </dev/null &
  CHANGED=1
  log "stale tailscaled (pid $pid, supervisor ${sup:-none}): $STALE_REASON; killed both and restarted"
  say 'tailscaled kept a stale proxy from before a restart; restarted it'
}

mkdir -p "$STATE_DIR"
# Appended to on every prompt, so it is trimmed rather than left to grow.
[ -f "$LOG" ] && [ "$(wc -c <"$LOG")" -gt 262144 ] && { tail -c 65536 "$LOG" >"$LOG.trim" && mv "$LOG.trim" "$LOG"; }
log "run: ts=$TS_DIR state=$STATE_DIR ssh=$SSH_DIR"

if [ ! -x "$TS_DIR/tailscaled" ] || [ ! -x "$TS_DIR/tailscale" ]; then
  say "tailscale binaries missing in $TS_DIR (cloud environment setup script not run)"
  exit 0
fi

ensure_ssh_config
write_supervisor
DAEMON_PID="$($PGREP_CMD -x tailscaled 2>/dev/null | head -n1)"
if [ -n "$DAEMON_PID" ] && daemon_is_stale "$DAEMON_PID"; then
  heal_stale_daemon "$DAEMON_PID"
  exit 0
elif [ -n "$DAEMON_PID" ]; then
  log "tailscaled is already running"
elif supervisor_alive; then
  log "the supervisor is already restarting tailscaled"
else
  setsid nohup bash "$STATE_DIR/supervise.sh" >/dev/null 2>&1 </dev/null &
  CHANGED=1
  log "started the supervisor"
fi

STATE="$(wait_for_state)"
log "backend state: ${STATE:-unreachable}"
# The only three states an auth key can fix. `up` speaks to the daemon over the
# same socket, so a daemon that never answered is not a login problem either.
case "$STATE" in
  NeedsLogin | NoState | Stopped)
    if [ -z "${TS_AUTHKEY:-}" ]; then
      say 'not logged in and TS_AUTHKEY is not set (add it to the cloud environment variables)'
      exit 0
    fi
    # Only the exit status is logged: tailscale quotes the key back in some of
    # its own error messages, and a model reads this file.
    "$TS_DIR/tailscale" --socket="$SOCKET" up --auth-key="$TS_AUTHKEY" \
      --hostname="$TS_HOSTNAME" --accept-dns=false --timeout=60s >/dev/null 2>&1
    log "tailscale up exited $?"
    CHANGED=1
    STATE="$(wait_for_state)"
    log "backend state after login: ${STATE:-unreachable}"
    ;;
esac
[ "$STATE" = "Running" ] || { say "tailscale is not running (state ${STATE:-unreachable}); see $LOG"; exit 0; }

if probe_ok; then
  [ "$CHANGED" = 1 ] && say 'wb reachable over tailscale'
  exit 0
fi
say 'tailnet up but wb:22 unreachable (Tailscale SSH check/ACL?)'
exit 0
