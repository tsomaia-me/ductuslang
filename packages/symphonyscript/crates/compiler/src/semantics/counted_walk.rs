    pub(crate) fn step(self) {
        #[cfg(test)]
        STEPS.with(|steps| {
            if let Some(step) = steps.get(self as usize) {
                step.set(step.get().saturating_add(1));
            }
        });
    }

    #[cfg(test)]
    pub(crate) fn steps(self) -> u64 {
        STEPS.with(|steps| steps.get(self as usize).map_or(0, std::cell::Cell::get))
    }
