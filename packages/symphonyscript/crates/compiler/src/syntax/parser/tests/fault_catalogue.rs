use std::ops::Range;

use crate::diagnostics::Code;

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub(super) enum Context {
    TopLevel,
    Body,
    TopBracket,
    BodyBracket,
    Bundle,
    ParenPlacement,
    OtherBracket,
}

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub(super) enum Lines {
    One,
    Across,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(super) enum BracketKind {
    Expression,
    Bundle,
    Other,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(super) enum Open {
    Closed,
    AfterFault,
    Unclosed { bracket: BracketKind, closer: Code },
}

pub(super) struct FaultItem {
    pub(super) code: Code,
    pub(super) context: Context,
    pub(super) lines: Lines,
    pub(super) text: String,
    pub(super) faults: Vec<(Code, Range<u32>)>,
    pub(super) open: Open,
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Hole {
    Number,
    Name,
    Text,
    Stray,
    LineEnd,
}

use self::BracketKind::{Bundle as InBundle, Expression, Other};
